"""Messages: reach out to community members.

Members are synthetic; their replies are generated by Claude in the member's voice
(llm.member_reply) and every thread says so. Threads live in this session only.
"""

from __future__ import annotations

import streamlit as st

import data
import llm
import nav
import ui

_THREADS = "msg_threads"


def _threads() -> dict:
    return st.session_state.setdefault(_THREADS, {})


def _open(mid: str) -> None:
    m = data.member_by_id(mid)
    th = _threads()
    if m and mid not in th:
        th[mid] = [{"role": "assistant", "content": m["intro_message"]}]
    st.session_state[nav.THREAD_KEY] = mid


def unread_hint() -> int:
    return len(_threads())


def render(user: dict) -> None:
    ui.page_intro("Messages", "Talk with women who've been there.",
                  "Ask about a job, a training program, or just the first few months. Mentors answer from their own experience.")
    members = data.load_members()
    active = st.session_state.get(nav.THREAD_KEY)
    if active and active not in _threads():
        _open(active)

    left, right = st.columns([1, 2.2], gap="large")
    with left:
        th = _threads()
        if th:
            st.html('<p class="rb-small rb-strong">Your conversations</p>')
            for mid in list(th):
                m = data.member_by_id(mid)
                if not m:
                    continue
                last = th[mid][-1]["content"]
                if st.button(f"{m['display_name']} — {last[:42]}…", key=f"thread_{mid}", use_container_width=True,
                             type="primary" if mid == active else "secondary"):
                    _open(mid)
                    st.rerun()
        tags = st.session_state.get("mp_tags") or {"industry": [], "experience": []}
        suggested = sorted([m for m in members if m.get("mentor") and m["id"] not in th],
                           key=lambda m: (-data.tag_overlap(tags, m), m["id"]))[:6]
        st.html('<p class="rb-small rb-strong" style="margin-top:16px">Mentors you can message</p>')
        for m in suggested:
            with st.container(key=f"card_sugg_{m['id']}"):
                st.html(f'<div class="rb-row" style="gap:12px;flex-wrap:nowrap">{ui.avatar(m["display_name"], 40)}'
                        f'<div class="rb-stack" style="gap:2px"><p class="rb-small rb-strong">{ui.esc(m["display_name"])}</p>'
                        f'<p class="rb-small rb-muted" style="font-size:14px">{ui.esc(m["current_job"])} · {ui.esc(m["last_active"])}</p></div></div>')
                if st.button("Message", key=f"sugg_{m['id']}", type="tertiary"):
                    _open(m["id"])
                    st.rerun()

    with right:
        m = data.member_by_id(active) if active else None
        if not m:
            st.html('<div class="rb-notice"><p class="rb-small">Pick a mentor to start a conversation. '
                    "You can also message women from their stories on the Community page.</p></div>")
    if not m:
        ui.footer()
        return
        helps = "".join(ui.pill(h, "small white") for h in m.get("can_help_with", []))
        tags_html = "".join(ui.pill(data.tag_label(t), "small") for t in m["industry_tags"])
        st.html(
            '<div class="rb-card" style="gap:10px">'
            f'<div class="rb-row" style="gap:14px;flex-wrap:nowrap">{ui.avatar(m["display_name"], 56)}'
            f'<div class="rb-stack" style="gap:2px;flex:1"><p class="rb-serif" style="font-size:24px">{ui.esc(m["display_name"])}</p>'
            f'<p class="rb-small rb-muted">{ui.esc(m["current_job"])} · {ui.esc(m["years_in_role"])} · {ui.esc(m["city"])}</p></div>'
            f'<span class="rb-pill small white">Example member · AI-simulated replies</span></div>'
            f'<p class="rb-small"><strong>{ui.esc(m["headline"])}</strong></p>'
            f'<div class="rb-row" style="gap:6px">{tags_html}{helps}</div>'
            f'<p class="rb-small rb-muted" style="font-size:14px">Usually around: {ui.esc(m["availability"])}</p></div>'
        )
        who = (user.get("name") or "You") if not user.get("guest") else "You"
        st.html('<div class="rb-stack" style="gap:18px;margin-top:12px" aria-live="polite">' + "".join(
            ui.chat_bubble("user" if x["role"] == "user" else "bot", who if x["role"] == "user" else m["first_name"], x["content"])
            for x in _threads()[m["id"]]) + "</div>")
        st.html('<p class="rb-small rb-muted" style="font-size:13px;margin-top:8px">Don’t share your full name, address, '
                "or case details. If you're in crisis, call or text 988 any time.</p>")

    text = st.chat_input(f"Message {m['first_name']}…", key="msg_composer", max_chars=1000)
    if text and text.strip():
        thread = _threads()[m["id"]]
        thread.append({"role": "user", "content": text.strip()})
        with st.spinner(f"{m['first_name']} is typing…"):
            reply = llm.member_reply(m, thread, (user.get("name") or "") if not user.get("guest") else "",
                                     st.session_state.get("mp_summary", ""))
        thread.append({"role": "assistant", "content": reply})
        st.rerun()
